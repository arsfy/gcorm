package dialect

import (
	"database/sql"
	stderrors "errors"
	"fmt"
	"strings"

	"github.com/arsfy/gcorm/pkg/runtime"
	gcoerr "github.com/arsfy/gcorm/pkg/runtime/errors"
)

// PostgreSQL implements the runtime.Dialect interface for PostgreSQL databases.
type PostgreSQL struct{}

func (PostgreSQL) Name() string { return "postgresql" }

func (PostgreSQL) Placeholder(n int) string { return fmt.Sprintf("$%d", n) }

func (PostgreSQL) QuoteIdent(parts ...string) string {
	quoted := make([]string, len(parts))
	for i, p := range parts {
		quoted[i] = `"` + strings.ReplaceAll(p, `"`, `""`) + `"`
	}
	return strings.Join(quoted, ".")
}

func (PostgreSQL) SupportsReturning() bool { return true }

func (PostgreSQL) SupportsSchemas() bool { return true }

func (PostgreSQL) RewriteLimitOffset(limit, offset *int) string {
	var sb strings.Builder
	if limit != nil {
		sb.WriteString(fmt.Sprintf("LIMIT %d", *limit))
	}
	if offset != nil {
		if sb.Len() > 0 {
			sb.WriteByte(' ')
		}
		sb.WriteString(fmt.Sprintf("OFFSET %d", *offset))
	}
	return sb.String()
}

// ClassifyError maps a PostgreSQL driver error to a DBError. Structured
// SQLSTATE codes (pgx *pgconn.PgError, lib/pq *pq.Error, or a "(SQLSTATE
// XXXXX)" suffix in the message) take precedence; message text is only
// inspected when no code is available. See postgresql_errors.go.
func (PostgreSQL) ClassifyError(err error) *runtime.DBError {
	if err == nil {
		return nil
	}

	if stderrors.Is(err, sql.ErrNoRows) {
		return gcoerr.Wrap(err, gcoerr.CodeNotFound, "record not found")
	}

	if details, ok := postgresErrorDetailsFromDriver(err); ok {
		return classifyPostgresSQLState(err, details)
	}
	return classifyPostgresMessage(err)
}

func (PostgreSQL) TypeMapping(schemaType string, isOptional bool) string {
	var t string
	switch schemaType {
	case "String":
		t = "TEXT"
	case "Int":
		t = "INTEGER"
	case "SmallInt":
		t = "SMALLINT"
	case "BigInt":
		t = "BIGINT"
	case "Float":
		t = "DOUBLE PRECISION"
	case "Decimal":
		t = "DECIMAL"
	case "Boolean":
		t = "BOOLEAN"
	case "DateTime":
		t = "TIMESTAMPTZ"
	case "Bytes":
		t = "BYTEA"
	case "Json":
		t = "JSONB"
	case "UUID":
		t = "UUID"
	default:
		t = "TEXT"
	}
	return t
}

func (PostgreSQL) DefaultValueExpression(funcName string, args []string) string {
	switch funcName {
	case "uuid":
		return "gen_random_uuid()"
	case "now":
		return "NOW()"
	case "autoincrement":
		return "GENERATED BY DEFAULT AS IDENTITY"
	case "cuid":
		// cuid() values are generated client-side; the column has no
		// database default.
		return ""
	case "dbgenerated":
		return dbGeneratedDefaultExpression(args)
	case "sequence":
		name := "unnamed_seq"
		if len(args) > 0 {
			name = unquoteSchemaString(args[0])
		}
		return "nextval(" + quoteSQLStringLiteral(name) + ")"
	default:
		return functionCallExpression(funcName, args)
	}
}

func (PostgreSQL) SupportsFeature(feature runtime.Feature) bool {
	switch feature {
	case runtime.FeatureReturning,
		runtime.FeatureSchemas,
		runtime.FeatureJSON,
		runtime.FeatureUUID,
		runtime.FeatureArrays,
		runtime.FeatureEnumType,
		runtime.FeatureCascadeDelete,
		runtime.FeatureIdentityColumn,
		runtime.FeatureUpsert,
		runtime.FeaturePartialIndex:
		return true
	case runtime.FeatureSerialType:
		return true
	default:
		return false
	}
}

// Compile-time check.
var _ runtime.Dialect = PostgreSQL{}
