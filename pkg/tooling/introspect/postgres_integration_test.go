// TestIntrospectPostgresSchemaCompiles introspects a live PostgreSQL schema
// covering identity/serial, bytea, enums, arrays, native types, json, uuid,
// generated columns and two FKs to one table, then compiles the generated
// schema text. It requires GCO_TEST_POSTGRES_URL.
func TestIntrospectPostgresSchemaCompiles(t *testing.T) {
	baseURL := os.Getenv("GCO_TEST_POSTGRES_URL")
	if baseURL == "" {
		t.Skip("GCO_TEST_POSTGRES_URL not set")
	}
	db, err := sql.Open("pgx", baseURL)
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()

	schemaName := fmt.Sprintf("gco_introspect_%d", time.Now().UnixNano())
	q := func(name string) string { return `"` + schemaName + `"."` + name + `"` }
	statements := []string{
		`CREATE SCHEMA "` + schemaName + `"`,
		`CREATE TYPE ` + q("order_status") + ` AS ENUM ('pending', 'in progress', 'DONE')`,
		`CREATE TABLE ` + q("users") + ` (
			id serial PRIMARY KEY,
			email varchar(20) NOT NULL UNIQUE,
			avatar bytea,
			tags text[] NOT NULL DEFAULT '{}',
			balance numeric(10,2) NOT NULL DEFAULT 0,
			seen_at timestamp(6),
			birthday date,
			meta json,
			prefs jsonb,
			external_id uuid NOT NULL DEFAULT gen_random_uuid(),
			token text NOT NULL DEFAULT 'uuid-v1',
			stamp text NOT NULL DEFAULT 'now()',
			status ` + q("order_status") + ` NOT NULL DEFAULT 'in progress',
			email_lower text GENERATED ALWAYS AS (lower((email)::text)) STORED
		)`,
		`CREATE TABLE ` + q("posts") + ` (
			id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			author_id integer NOT NULL REFERENCES ` + q("users") + `(id),
			editor_id integer REFERENCES ` + q("users") + `(id),
			title text NOT NULL,
			created_at timestamptz NOT NULL DEFAULT now()
		)`,
		`CREATE INDEX posts_title_idx ON ` + q("posts") + ` (title DESC NULLS LAST)`,
	}
	defer db.Exec(`DROP SCHEMA IF EXISTS "` + schemaName + `" CASCADE`)
	for _, stmt := range statements {
		if _, err := db.Exec(stmt); err != nil {
			t.Fatalf("%s: %v", stmt, err)
		}
	}

	introspectURL := withQueryParam(t, baseURL, "schema", schemaName)
	outDir := t.TempDir()
	if err := Run([]string{"--url", introspectURL, "--provider", "postgresql", "--output", outDir}); err != nil {
		t.Fatalf("Run: %v", err)
	}
	data, err := os.ReadFile(filepath.Join(outDir, "schema.gcorm"))
	if err != nil {
		t.Fatal(err)
	}
	content := string(data)
	t.Logf("generated schema:\n%s", content)

	result := compiler.CompileFile("schema.gcorm", data)
	if result.HasErrors() {
		t.Fatalf("generated schema does not compile: %v\n%s", result.Errors, content)
	}

	for _, want := range []string{
		`enum OrderStatus {`,
		`in_progress @map("in progress")`,
		`@@map("order_status")`,
		`@default(autoincrement())`,
		`@unique @db.VarChar(20)`,
		`Bytes?`,
		`String[]`,
		`@default(0) @db.Decimal(10, 2)`,
		`DateTime? @db.Timestamp(6)`,
		`Json?`,
		`UUID @default(uuid())`,
		`@default("uuid-v1")`,
		`@default("now()")`,
		`OrderStatus @default(in_progress)`,
		`DateTime @default(now())`,
		`@@index([title], name: "posts_title_idx", sort: Desc, nulls: Last`,
		`schema   = "` + schemaName + `"`,
	} {
		if !strings.Contains(content, want) {
			t.Errorf("generated schema missing %q", want)
		}
	}
	for _, re := range []string{
		`(?m)^\s+id\s+Int @id @default\(autoincrement\(\)\)$`,
		`(?m)^\s+token\s+String @default\("uuid-v1"\)$`,
		`(?m)^\s+stamp\s+String @default\("now\(\)"\)$`,
		`(?m)^\s+author\s+Users @relation\(fields: \[author_id\], references: \[id\]`,
		`(?m)^\s+editor\s+Users\? @relation\(fields: \[editor_id\], references: \[id\]`,
		`(?m)^\s+posts_author\s+Posts\[\]$`,
		`(?m)^\s+posts_editor\s+Posts\[\]$`,
	} {
		if !regexp.MustCompile(re).MatchString(content) {
			t.Errorf("generated schema does not match %s", re)
		}
	}

	// Columns whose catalog details come from dbpush must be represented
	// faithfully: generated columns, and the native type of every field.
	normalized, err := dbpush.NormalizeConnectionURL(introspectURL, "postgresql")
	if err != nil {
		t.Fatal(err)
	}
	ndb, err := sql.Open("pgx", normalized)
	if err != nil {
		t.Fatal(err)
	}
	defer ndb.Close()
	live, err := dbpush.IntrospectDatabase(context.Background(), ndb, "postgresql", nil, normalized)
	if err != nil {
		t.Fatal(err)
	}
	for _, model := range live.Models {
		for _, f := range model.ScalarFields() {
			if f.IsGenerated {
				if !strings.Contains(content, f.Name+" is a read-only generated column") ||
					!strings.Contains(content, `@default(dbgenerated(`) {
					t.Errorf("generated column %s.%s is not marked read-only with dbgenerated()", model.Name, f.Name)
				}
			}
			if f.NativeType != nil && !strings.Contains(content, nativeTypeAttribute(f.NativeType)) {
				t.Errorf("native type of %s.%s (%s) missing", model.Name, f.Name, nativeTypeAttribute(f.NativeType))
			}
		}
	}
	compiledUsers := findModelByTable(result.Schema, "users")
	if compiledUsers == nil {
		t.Fatalf("compiled schema has no users model")
	}
	if f := findFieldByDBName(compiledUsers, "status"); f == nil || f.Type != ir.FieldKindEnum || f.Default == nil || f.Default.Value != "in_progress" {
		t.Errorf("compiled status field = %#v", f)
	}
	if f := findFieldByDBName(compiledUsers, "tags"); f == nil || !f.IsList {
		t.Errorf("compiled tags field = %#v", f)
	}
}

func withQueryParam(t *testing.T, raw, key, value string) string {
	t.Helper()
	u, err := url.Parse(raw)
	if err != nil {
		t.Fatal(err)
	}
	query := u.Query()
	query.Set(key, value)
	u.RawQuery = query.Encode()
	return u.String()
}

func findModelByTable(schema *ir.Schema, table string) *ir.Model {
	if schema == nil {
		return nil
	}
	for _, model := range schema.Models {
		if model.TableName() == table {
			return model
		}
	}
	return nil
}

func findFieldByDBName(model *ir.Model, column string) *ir.Field {
	for _, f := range model.Fields {
		if f.DBName == column || (f.DBName == "" && f.Name == column) {
			return f
		}
	}
	return nil
}
