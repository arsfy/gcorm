func TestBaseImportPath(t *testing.T) {
	t.Run("explicit module path trims trailing slash", func(t *testing.T) {
		g := &Generator{modulePath: "example.com/acme/", output: "./gen"}
		if got := g.baseImportPath(); got != "example.com/acme" {
			t.Errorf("baseImportPath() = %q, want %q", got, "example.com/acme")
		}
	})

	t.Run("explicit module path ignores output", func(t *testing.T) {
		g := &Generator{modulePath: "example.com/acme/gen", output: "./elsewhere"}
		if got := g.baseImportPath(); got != "example.com/acme/gen" {
			t.Errorf("baseImportPath() = %q, want %q", got, "example.com/acme/gen")
		}
	})

	t.Run("detected module path combines with output", func(t *testing.T) {
		dir := t.TempDir()
		if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module example.com/acme\n\ngo 1.26.1\n"), 0o644); err != nil {
			t.Fatal(err)
		}
		t.Chdir(dir)

		g := &Generator{output: "./gen"}
		if got := g.baseImportPath(); got != "example.com/acme/gen" {
			t.Errorf("baseImportPath() = %q, want %q", got, "example.com/acme/gen")
		}

		g = &Generator{output: "gen"}
		if got := g.baseImportPath(); got != "example.com/acme/gen" {
			t.Errorf("baseImportPath() = %q, want %q", got, "example.com/acme/gen")
		}

		g = &Generator{output: "."}
		if got := g.baseImportPath(); got != "example.com/acme" {
			t.Errorf("baseImportPath() = %q, want %q", got, "example.com/acme")
		}

		g = &Generator{output: ""}
		if got := g.baseImportPath(); got != "example.com/acme" {
			t.Errorf("baseImportPath() = %q, want %q", got, "example.com/acme")
		}
	})

	t.Run("no module found yields empty base", func(t *testing.T) {
		t.Chdir(t.TempDir())
		g := &Generator{output: "./gen"}
		if got := g.baseImportPath(); got != "" {
			t.Errorf("baseImportPath() = %q, want %q", got, "")
		}
	})

	t.Run("output paths resolve relative to the module root", func(t *testing.T) {
		dir := t.TempDir()
		if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module example.com/acme\n"), 0o644); err != nil {
			t.Fatal(err)
		}
		nested := filepath.Join(dir, "nested")
		if err := os.Mkdir(nested, 0o755); err != nil {
			t.Fatal(err)
		}
		t.Chdir(nested)
		for _, tc := range []struct{ output, want string }{
			{"./gen", "example.com/acme/nested/gen"},
			{"../gen", "example.com/acme/gen"},
			{filepath.Join(dir, "gen"), "example.com/acme/gen"},
		} {
			g := &Generator{output: tc.output}
			if got := g.baseImportPath(); got != tc.want {
				t.Errorf("output %q: baseImportPath() = %q, want %q", tc.output, got, tc.want)
			}
		}
	})
}

func TestFindModule(t *testing.T) {
	t.Run("finds module in current directory", func(t *testing.T) {
		dir := t.TempDir()
		if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module example.com/root\n\ngo 1.26.1\n"), 0o644); err != nil {
			t.Fatal(err)
		}
		if got, root := findModule(dir); got != "example.com/root" || root != dir {
			t.Errorf("findModule() = %q, %q, want %q, %q", got, root, "example.com/root", dir)
		}
	})

	t.Run("walks up from nested directory", func(t *testing.T) {
		dir := t.TempDir()
		if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module example.com/root\n"), 0o644); err != nil {
			t.Fatal(err)
		}
		nested := filepath.Join(dir, "a", "b")
		if err := os.MkdirAll(nested, 0o755); err != nil {
			t.Fatal(err)
		}
		if got, root := findModule(nested); got != "example.com/root" || root != dir {
			t.Errorf("findModule() = %q, %q, want %q, %q", got, root, "example.com/root", dir)
		}
	})

	t.Run("go.mod without module line keeps walking up", func(t *testing.T) {
		dir := t.TempDir()
		if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module example.com/root\n"), 0o644); err != nil {
			t.Fatal(err)
		}
		nested := filepath.Join(dir, "inner")
		if err := os.MkdirAll(nested, 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(nested, "go.mod"), []byte("go 1.26.1\n"), 0o644); err != nil {
			t.Fatal(err)
		}
		if got, root := findModule(nested); got != "example.com/root" || root != dir {
			t.Errorf("findModule() = %q, %q, want %q, %q", got, root, "example.com/root", dir)
		}
	})

	t.Run("returns empty when no go.mod exists", func(t *testing.T) {
		if got, root := findModule(t.TempDir()); got != "" || root != "" {
			t.Errorf("findModule() = %q, %q, want empty module and root", got, root)
		}
	})
}

