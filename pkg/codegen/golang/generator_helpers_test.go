func TestRenderTemplateFuncMapClosures(t *testing.T) {
	s := testSchema()
	g := NewGenerator(s)
	tmpl := `package p

var name = {{quote "users"}}
var table = {{quotedTableName .Model}}
var cols = []string{ {{quotedColumnCSV .Model}} }
`
	content, err := g.renderTemplate("funcs", tmpl, map[string]any{"Model": s.Models[0]})
	if err != nil {
		t.Fatalf("renderTemplate() error: %v", err)
	}
	out := string(content)
	if !strings.Contains(out, `var name = "users"`) {
		t.Errorf("quote closure not applied:\n%s", out)
	}
	if !strings.Contains(out, `var table = "users"`) {
		t.Errorf("quotedTableName closure not applied:\n%s", out)
	}
	if !strings.Contains(out, `var cols = []string{"id", "email", "name", "role", "age", "rank", "created_at"}`) {
		t.Errorf("quotedColumnCSV closure not applied:\n%s", out)
	}
}

