func TestNewGeneratorDefaults(t *testing.T) {
	g := NewGenerator(&ir.Schema{})
	if g.pkg != "db" {
		t.Errorf("pkg = %q, want %q", g.pkg, "db")
	}
	if g.output != "./gen" {
		t.Errorf("output = %q, want %q", g.output, "./gen")
	}
	if g.dialect != "postgresql" {
		t.Errorf("dialect = %q, want %q", g.dialect, "postgresql")
	}

	// Generator entries with empty fields keep the defaults.
	g = NewGenerator(&ir.Schema{
		Generators: []*ir.Generator{{Name: "go"}},
		Datasource: &ir.Datasource{Provider: "mysql"},
	})
	if g.pkg != "db" || g.output != "./gen" {
		t.Errorf("pkg/output = %q/%q, want db/./gen", g.pkg, g.output)
	}
	if g.dialect != "mysql" {
		t.Errorf("dialect = %q, want %q", g.dialect, "mysql")
	}
}

