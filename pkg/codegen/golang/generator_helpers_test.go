func TestUniqueFields(t *testing.T) {
	m := &ir.Model{
		Name: "User",
		Fields: []*ir.Field{
			{Name: "id", Type: ir.FieldKindScalar, ScalarType: "String", IsID: true},
			{Name: "email", Type: ir.FieldKindScalar, ScalarType: "String", IsUnique: true},
			{Name: "name", Type: ir.FieldKindScalar, ScalarType: "String"},
			{Name: "posts", Type: ir.FieldKindRelation, ModelType: "Post", IsList: true},
		},
	}

	got := uniqueFields(m)
	if len(got) != 2 {
		t.Fatalf("uniqueFields() returned %d fields, want 2", len(got))
	}
	if got[0].Name != "id" || got[1].Name != "email" {
		t.Errorf("uniqueFields() = [%s %s], want [id email]", got[0].Name, got[1].Name)
	}

	plain := &ir.Model{
		Name: "Plain",
		Fields: []*ir.Field{
			{Name: "name", Type: ir.FieldKindScalar, ScalarType: "String"},
		},
	}
	if got := uniqueFields(plain); len(got) != 0 {
		t.Errorf("uniqueFields() returned %d fields for model without id/unique, want 0", len(got))
	}
}

